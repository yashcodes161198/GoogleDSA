import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { PGlite } from './db-runtime/node_modules/@electric-sql/pglite/dist/index.js';
const db = new PGlite();
const owner = '00000000-0000-0000-0000-000000000001';
const problem = '00000000-0000-0000-0000-000000000003';
try {
  await db.exec(`CREATE ROLE authenticated NOLOGIN; CREATE ROLE anon NOLOGIN;
    CREATE SCHEMA auth; CREATE TABLE auth.users(id UUID PRIMARY KEY,email TEXT,raw_user_meta_data JSONB);
    CREATE FUNCTION auth.uid() RETURNS UUID LANGUAGE sql STABLE AS $$ SELECT NULLIF(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    GRANT USAGE ON SCHEMA auth TO authenticated, anon;
    CREATE TABLE public.problems(id UUID PRIMARY KEY,difficulty TEXT);
    INSERT INTO auth.users VALUES ('${owner}','fixture@example.invalid','{}');
    INSERT INTO problems VALUES ('${problem}','HARD');`);
  await db.exec(await readFile('supabase/migrations/013_leaderboard.sql','utf8'));
  await db.exec(await readFile('supabase/migrations/016_delete_own_score_events.sql','utf8'));
  await db.exec('SET ROLE authenticated');
  await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)",[owner]);
  const solve = (await db.query('SELECT award_leaderboard_solve($1) AS points',[problem])).rows[0].points;
  const revision = (await db.query('SELECT award_leaderboard_revision($1,1000000) AS points',[problem])).rows[0].points;
  const nextRevision = (await db.query('SELECT award_leaderboard_revision($1,1000001) AS points',[problem])).rows[0].points;
  assert.equal(solve,8); assert.equal(revision,2); assert.equal(nextRevision,2);
  await db.query("DELETE FROM leaderboard_events WHERE event_type='solve'");
  const replay = (await db.query('SELECT award_leaderboard_solve($1) AS points',[problem])).rows[0].points;
  assert.equal(replay,8);
  const result = { isolatedPostgres: true, migrations: [13,16], progressTableExists: false, solveWithoutProgressPoints: solve, fabricatedRevision1000000Points: revision, fabricatedRevision1000001Points: nextRevision, solveAfterDeletionPoints: replay };
  await db.exec('RESET ROLE');
  await db.exec(await readFile('supabase/migrations/017_leaderboard_comments.sql','utf8'));
  const mediaMigration = await readFile('supabase/migrations/018_leaderboard_comment_media.sql','utf8');
  await db.exec(mediaMigration.slice(mediaMigration.indexOf('ALTER TABLE public.leaderboard_comments')));
  await db.exec(await readFile('supabase/migrations/019_edit_own_leaderboard_comments.sql','utf8'));
  await db.exec('SET ROLE authenticated');
  await db.query("INSERT INTO leaderboard_comments(user_id,body,created_at) VALUES ($1,'fixture','infinity')",[owner]);
  const timestamp = (await db.query("SELECT to_jsonb(c)->>'created_at' AS timestamp FROM get_leaderboard_comments() c")).rows[0].timestamp;
  assert.equal(timestamp,'infinity');
  assert.throws(() => new Intl.DateTimeFormat('en-IN').format(new Date(timestamp)),RangeError);
  result.commentTimestamp = timestamp;
  result.commentMigrations = '017, comment schema/policies/RPC from 018, 019; Storage service not emulated';
  result.commentDateFormatterThrows = true;
  await db.exec('RESET ROLE');
  await db.exec('CREATE TABLE interview_session_problems(position INTEGER CHECK(position BETWEEN 1 AND 5))');
  await db.exec(await readFile('supabase/migrations/007_custom_interview_size.sql','utf8'));
  await assert.rejects(db.query('INSERT INTO interview_session_problems VALUES (21)'),/check constraint/);
  result.pickedPosition21Rejected = true;
  await writeFile(new URL('./award-boundary-results.json',import.meta.url),JSON.stringify(result,null,2));
  console.log(JSON.stringify(result));
} finally { await db.close(); }
